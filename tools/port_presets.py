#!/usr/bin/env python3
"""Generates core/drum_presets.c from thump's Presets.cpp: the 58 drums and the 12 kits, parameter names mapped by
their position in thump's enum (Params.h) onto ours (core/drum.h), which keeps the same order.
Usage: tools/port_presets.py ~/Projects/thump > core/drum_presets.c"""
import re, sys, pathlib

thump = pathlib.Path(sys.argv[1])
here = pathlib.Path(__file__).resolve().parent.parent

def enum_names(text, start, stop):
    body = text[text.index(start) + (len(start) if start.endswith('{') else 0):]
    body = body[:body.index(stop)]
    body = re.sub(r'//[^\n]*', '', body)
    return [n.strip() for n in body.replace('\n', ' ').split(',') if n.strip() and not n.strip().startswith(('enum', '{'))]

params_h = (thump / 'src/dsp/Params.h').read_text()
ours_h = (here / 'core/drum.h').read_text()
theirs = enum_names(params_h, 'enum P : int {', 'kNumParams')
ours = enum_names(ours_h, 'P_TYPE,', 'DRUM_NP')
assert len(theirs) == len(ours), (len(theirs), len(ours))
pmap = dict(zip(theirs, ours))
tmap = {'Kick': 'DT_KICK', 'Snare': 'DT_SNARE', 'Clap': 'DT_CLAP', 'Rim': 'DT_RIM', 'Hat': 'DT_HAT', 'Tom': 'DT_TOM', 'Perc': 'DT_PERC'}

src = (thump / 'src/dsp/Presets.cpp').read_text()
drums_src = re.sub(r'//[^\n]*', '', src[src.index('drumPresets()'):src.index('findDrum')])
drums = re.findall(r'\{\s*"([^"]+)",\s*"([^"]+)",\s*T::(\w+),\s*\{(.*?)\}\s*\},?\s*(?=\{\s*"|\};)', drums_src, re.S)
kits_src = src[src.index('kitPresets()'):src.index('patternFrom')]
kits = re.findall(r'\{\s*"([^"]+)",\s*"([^"]+)",\s*\{([^}]*)\},\s*\{([^}]*)\},\s*([\d.]+),\s*([\d.f]+)\s*\}', kits_src, re.S)

out = []
out.append('// Generated by tools/port_presets.py from thump\'s Presets.cpp. Levels are filled in by tools (see drum_levels).')
out.append('#include "presets.h"')
out.append('')
for i, (name, genre, typ, body) in enumerate(drums):
    pairs = re.findall(r'\{\s*(p\w+)\s*,\s*([-\d.]+)f?\s*\}', body)
    items = ', '.join('{ %s, %sf }' % (pmap[p], v if '.' in v else v + '.0') for p, v in pairs)
    out.append('static const drum_pv_t set%d[] = { %s, { -1, 0 } };' % (i, items))
out.append('')
out.append('const drum_preset_t drum_presets[] = {')
for i, (name, genre, typ, body) in enumerate(drums):
    out.append('    { "%s", "%s", %s, set%d },' % (name, genre, tmap[typ], i))
out.append('};')
out.append('const int drum_preset_count = %d;' % len(drums))
out.append('')
out.append('const kit8_t kit8_presets[] = {')
for name, genre, dr, rows, tempo, swing in kits:
    dnames = re.findall(r'"([^"]+)"', dr)
    rws = re.findall(r'"([^"]+)"', rows)
    assert len(dnames) == 8 and len(rws) == 8, name
    out.append('    { "%s", "%s", { %s },' % (name, genre, ', '.join('"%s"' % d for d in dnames)))
    out.append('      { %s }, %s, %s },' % (', '.join('"%s"' % r for r in rws), tempo, swing.rstrip('f') + 'f'))
out.append('};')
out.append('const int kit8_count = %d;' % len(kits))
print('\n'.join(out))
print('// %d drums, %d kits' % (len(drums), len(kits)), file=sys.stderr)
