#!/usr/bin/env python3
"""Bitmap fonts for the screen, from the Terminus bitmap fonts (SIL Open Font License 1.1) the mockups were drawn
with: the same sizes, rendered the same way (PIL, no smoothing), so the screen looks like docs/mockups.
Usage: tools/mkfont.py > core/font_data.c"""
from PIL import Image, ImageDraw, ImageFont

FD = '/usr/share/fonts/misc/'
FONTS = [('F12', 'ter-u12n', 12), ('F12B', 'ter-u12b', 12), ('F14', 'ter-u14b', 14), ('F14N', 'ter-u14n', 14),
         ('F16', 'ter-u16b', 16), ('F20', 'ter-u20b', 20), ('F24', 'ter-u24b', 24), ('F32', 'ter-u32b', 32)]
EXTRA = '×·—…←↑→↓↕●■▲▼►◄✓✗°±♪♫'
CHARS = [chr(c) for c in range(32, 127)] + list(EXTRA)

out = ['// Generated by tools/mkfont.py from the Terminus fonts (SIL Open Font License 1.1, Dimitar Zhekov).',
       '#include "font.h"', '']
for name, file, size in FONTS:
    f = ImageFont.truetype(FD + file + '.otb', size)
    w = int(f.getlength('M'))
    bpr = (w + 7) // 8
    rows = []
    for ch in CHARS:
        im = Image.new('L', (w + 8, size + 8), 0)
        d = ImageDraw.Draw(im); d.fontmode = '1'
        d.text((0, 0), ch, font=f, fill=255)
        bb = im.getbbox()
        assert not bb or (bb[2] <= w and bb[3] <= size), (file, ch, bb)
        data = []
        for y in range(size):
            bits = 0
            for x in range(w):
                if im.getpixel((x, y)): bits |= 1 << (bpr * 8 - 1 - x)
            data += [(bits >> (8 * (bpr - 1 - k))) & 255 for k in range(bpr)]
        rows.append(data)
    out.append('static const uint8_t %s_bits[] = {' % name.lower())
    for ch, data in zip(CHARS, rows):
        out.append('    ' + ', '.join('0x%02x' % b for b in data) + ',  // U+%04X' % ord(ch))
    out.append('};')
    out.append('const font_t %s = { %d, %d, %d, %s_bits };' % (name.lower(), w, size, bpr, name.lower()))
    out.append('')
out.append('const uint16_t font_codes[] = { %s };' % ', '.join('0x%04x' % ord(c) for c in CHARS))
out.append('const int font_ncodes = %d;' % len(CHARS))
print('\n'.join(out))
